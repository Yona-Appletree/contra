/**
 * `docs/motion-report.md`: the whole instrument, as one page somebody can read
 * on a phone.
 *
 * It is pure — it returns a string and writes nothing — so it can be tested
 * and so the file writing stays in `scripts/reportMotion.mjs`, which is what
 * `pnpm report:motion` runs.
 */

/** How long each dance is measured for: two times through. */
export const REPORT_BEATS: Beat = 128;

/** How many rows of each table the report prints. */
export const REPORT_ROWS = 10;

/** The whole report, as markdown. */
export function motionReportMarkdown(): string {
  const out: string[] = [];
  out.push("# The motion report");
  out.push("");
  out.push(
    "Generated by `pnpm report:motion` (F3a). It measures how the **drawn arm** moves — " +
      "the hand and the elbow the renderer actually puts on the screen, through " +
      "`@caller/core`'s `drawnArms` — over every demo dance and every figure in the " +
      "registry, and checks each figure against what a caller would say it does.",
  );
  out.push("");
  out.push("Nothing in here is a pass/fail gate. It is the thing to read before fixing a figure.");
  out.push("");

  out.push(...boundsSection());
  out.push(...dancesSection());
  out.push(...figuresSection());
  out.push(...knownWrongSection());
  out.push(...checksSection());
  out.push(...describeSection());
  return out.join("\n") + "\n";
}

