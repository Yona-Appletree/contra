/** The motion oracle over the demo dances. */
function dancesSection(): string[] {
  const out: string[] = ["## Over the demo dances", ""];
  out.push(
    `Each dance run alone by the script decider for two times through (beats 0–${REPORT_BEATS}), ` +
      "duple improper and proper at 4 couples and becket at 6, sampled every 1/32 beat.",
    "",
  );

  const figures = new Map<string, MotionStats>();
  const seams = new Map<string, MotionStats>();
  let overall: MotionStats | undefined;
  for (const dance of DEMO_DANCES) {
    const couples = linesFor(dance).includes(6) && isBecket(dance) ? 6 : 4;
    // **On the engine the dance ships on**, which since M11 is the only one
    // there is. This report used to measure every dance written before M5 on
    // the decider's own planner and the rest on the contra planner, because the
    // two differed by up to 1.16 px at the ends of a line (M3's cycle-start
    // switch) and switching them all over was a rewrite rather than a
    // milestone's business. The coded layer the old planner needed is deleted,
    // so the whole table is the shipped path now — which is what it should
    // always have been measuring.
    const decider = danceAlone(dance, couples, REPORT_BEATS, {}, LAB_RUN);
    const report = motionReport(decider.timeline(), REPORT_BEATS, {
      bounds: CONTRA_MOTION_BOUNDS,
    });
    for (const row of report.figures) merge(figures, row);
    for (const row of report.seams) merge(seams, row);
    overall = overall ? mergeInto(overall, report.overall) : { ...report.overall };
  }

  out.push(
    "### The ten worst figures",
    "",
    ...table([...figures.values()].sort(worstFirst).slice(0, REPORT_ROWS)),
    "",
    "### The ten worst seams",
    "",
    ...table([...seams.values()].sort(worstFirst).slice(0, REPORT_ROWS)),
    "",
  );
  if (overall) {
    out.push(
      `Over all ten dances: ${overall.samples.toLocaleString("en-GB")} measurements, ` +
        `${overall.stateFlips} hand-state flips, **${overall.nonFinite} of them not a finite number**.`,
      "",
    );
  }
  return out;
}

/** The motion oracle over each figure of the registry, alone. */
function figuresSection(): string[] {
  const out: string[] = ["## Every figure, alone", ""];
  out.push(
    "Each figure run on its own in a duple improper group of four, with nothing before",
    "it, so every number is the figure's own and no seam is folded in.",
    "",
  );
  out.push(...table(figureAloneRows()));
  out.push("");
  return out;
}

/**
 * One figure on its own timeline, measured; worst first.
 *
 * Every coded figure, and since M5 the **data-only** ones the hands-four
 * template can plan too — the hey among them, whose coded twin this milestone
 * deleted. A figure resolution mints per pair (`pull-by`, `shoulder-round`) or
 * over a whole line (`grand-right-and-left`) cannot be run on a group of four
 * and is not in this table; M7's shapes with named places are what would give
 * those a figure-alone row.
 */
export function figureAloneRows(): MotionStats[] {
  const rows: MotionStats[] = [];
  for (const id of dataOnlyFigureIds()) {
    // **Whatever a hands-four can plan** (M11). It used to be the coded
    // figures plus the data-only ones a bare template could plan; the coded
    // ones are gone and `figureOnFour` is the one predicate left — it mints the
    // pair instances a minor set implies, so the swing and its kind keep the
    // row their coded twins used to give them.
    const alone = figureOnFour(id);
    if (alone === undefined) continue;
    const registry = createContraRegistry([alone as AnyFigureDef]);
    const def = registry.get(id);
    const group = checkGroup();
    const timeline = createTimeline(registry);
    timeline.addGroup(group);
    const bindings: Record<string, string> = {};
    for (const station of group.stations) bindings[station.id] = station.id;
    timeline.add({
      kind: "figure",
      group: group.id,
      figure: id,
      params: withDefaults(def, {}, def.beats),
      bindings,
      start: 0,
      end: def.beats,
    });
    const report = motionReport(timeline, def.beats, { bounds: CONTRA_MOTION_BOUNDS });
    const row = report.figures[0];
    if (row) rows.push(row);
  }
  return rows.sort(worstFirst);
}

/** The known-wrong table. */
function knownWrongSection(): string[] {
  const out: string[] = ["## Known wrong", ""];
  out.push(
    "Every assertion below fails today and is **expected** to. The contract the tests",
    "hold is that everything *not* on this list passes and everything *on* it still",
    "fails, so a fix has to delete its row. Nothing is skipped; nothing was loosened.",
    "",
    "| figure or seam | assertion | measured | why |",
    "| --- | --- | --- | --- |",
  );
  for (const row of KNOWN_WRONG) {
    out.push(`| \`${row.key}\` | ${row.label} | ${row.measured} | ${row.why} |`);
  }
  out.push("");
  return out;
}

/** Every trajectory assertion, with its evidence. */
function checksSection(): string[] {
  const out: string[] = ["## What each figure actually does", ""];
  for (const group of figureChecks()) {
    out.push(`### \`${group.key}\``);
    out.push("");
    if (group.describe) {
      out.push(`> ${group.describe}`);
      out.push("");
    }
    out.push("| | assertion | evidence |");
    out.push("| --- | --- | --- |");
    for (const result of group.results) {
      const mark = result.pass
        ? "pass"
        : isKnownWrong(group.key, result.label)
          ? "**known**"
          : "**FAIL**";
      out.push(`| ${mark} | ${result.label} | ${result.note} |`);
    }
    out.push("");
  }
  return out;
}

/** The `describe` of every figure in the registry, and which are unsure. */
function describeSection(): string[] {
  const registry = createContraRegistry();
  const out: string[] = ["## What every figure says it does", ""];
  out.push(
    "These are the specifications the assertions above are written against. Anything",
    "marked `(unsure: …)` is a guess a caller should correct.",
    "",
  );
  for (const id of registry.ids().sort()) {
    const def = registry.get(id);
    out.push(`### \`${id}\` — ${def.call}`);
    out.push("");
    out.push(def.describe ?? "_no description._");
    out.push("");
  }
  return out;
}

/** Merge one dance's row into the running total for that key. */
function merge(rows: Map<string, MotionStats>, row: MotionStats): void {
  const found = rows.get(row.key);
  if (!found) {
    rows.set(row.key, { ...row });
    return;
  }
  rows.set(row.key, mergeInto(found, row));
}

/** The worse of two rows, field by field. */
function mergeInto(a: MotionStats, b: MotionStats): MotionStats {
  const worse = <
    K extends
      | "handSpeed"
      | "elbowSpeed"
      | "elbowPerHand"
      | "heightRate"
      | "travel"
      | "roleSpread"
      | "partSpread"
      | "elbowHeightRate"
      | "flipJump"
      | "dip",
  >(
    key: K,
  ) => (b[key].value > a[key].value ? b[key] : a[key]);
  return {
    key: a.key,
    handSpeed: worse("handSpeed"),
    elbowSpeed: worse("elbowSpeed"),
    elbowPerHand: worse("elbowPerHand"),
    heightRate: worse("heightRate"),
    travel: worse("travel"),
    roleSpread: worse("roleSpread"),
    partSpread: worse("partSpread"),
    elbowHeightRate: worse("elbowHeightRate"),
    flipJump: worse("flipJump"),
    dip: worse("dip"),
    stateFlips: a.stateFlips + b.stateFlips,
    ...((a.firstFlip ?? b.firstFlip) ? { firstFlip: a.firstFlip ?? b.firstFlip } : {}),
    nonFinite: a.nonFinite + b.nonFinite,
    ...((a.firstNonFinite ?? b.firstNonFinite)
      ? { firstNonFinite: a.firstNonFinite ?? b.firstNonFinite }
      : {}),
    reversals: a.reversals + b.reversals,
    samples: a.samples + b.samples,
  };
}

/** Worst first, by how far each row is over its bound. */
function worstFirst(a: MotionStats, b: MotionStats): number {
  return severity(b) - severity(a) || a.key.localeCompare(b.key);
}

function severity(s: MotionStats): number {
  return Math.max(
    s.handSpeed.value / CONTRA_MOTION_BOUNDS.handSpeedPx,
    s.elbowSpeed.value / CONTRA_MOTION_BOUNDS.elbowSpeedPx,
    s.elbowPerHand.value / CONTRA_MOTION_BOUNDS.elbowPerHand,
    s.heightRate.value / CONTRA_MOTION_BOUNDS.heightRatePx,
    s.travel.value / CONTRA_MOTION_BOUNDS.travelPx,
    s.roleSpread.value / CONTRA_MOTION_BOUNDS.spread,
    s.partSpread.value / CONTRA_MOTION_BOUNDS.spread,
    s.dip.value / CONTRA_MOTION_BOUNDS.dipPx,
    s.stateFlips > 0 ? 1 : 0,
    s.nonFinite > 0 ? 1000 : 0,
  );
}

const HEADER = [
  "| what | hand px/beat | elbow px/beat | elbow/hand | height px/beat | travel px/beat | roles × | halves × | flips | jump px | NaN | dip px | worst hand at |",
  "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | --- |",
];

function table(rows: readonly MotionStats[]): string[] {
  if (rows.length === 0) return ["_nothing measured._"];
  return [
    ...HEADER,
    ...rows.map(
      (r) =>
        `| \`${r.key}\` | ${over(r.handSpeed.value, CONTRA_MOTION_BOUNDS.handSpeedPx)} | ` +
        `${over(r.elbowSpeed.value, CONTRA_MOTION_BOUNDS.elbowSpeedPx)} | ` +
        `${over(r.elbowPerHand.value, CONTRA_MOTION_BOUNDS.elbowPerHand, 2)} | ` +
        `${over(r.heightRate.value, CONTRA_MOTION_BOUNDS.heightRatePx)} | ` +
        `${over(r.travel.value, CONTRA_MOTION_BOUNDS.travelPx)} | ` +
        `${spread(r.roleSpread.value)} | ${spread(r.partSpread.value)} | ${r.stateFlips} | ` +
        `${over(r.flipJump.value, CONTRA_MOTION_BOUNDS.handSpeedPx * MOTION_STEP, 2)} | ` +
        `${r.nonFinite} | ${over(r.dip.value, CONTRA_MOTION_BOUNDS.dipPx, 2)} | ${where(r)} |`,
    ),
  ];
}

/** A number, marked when it is over its bound. */
const over = (value: number, bound: number, places = 1): string =>
  value > bound ? `**${value.toFixed(places)}**` : value.toFixed(places);

/** A spread, marked when it is over the one bound the two share; `—` unmeasured. */
const spread = (value: number): string =>
  value <= 0 ? "—" : over(value, CONTRA_MOTION_BOUNDS.spread, 2);

const where = (r: MotionStats): string =>
  r.handSpeed.dancer === undefined
    ? "—"
    : `\`${r.handSpeed.dancer}\` ${r.handSpeed.side} at beat ${r.handSpeed.beat!.toFixed(3)}`;

