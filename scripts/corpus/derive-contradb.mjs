#!/usr/bin/env node
// Turns the raw ContraDB page cache into structured records:
// corpus-raw/contradb/<id>.html  →  derived/contradb/<id>.json, in the shape
// docs/corpus-derived.md defines under "derived/contradb/<id>.json".
//
// Why a parser at all: ContraDB serves a dance's figures only as rendered
// HTML — there is no JSON export of them — and that HTML is the only public
// source of the one thing The Caller's Box does not carry, the per-figure
// progression mark (the trailing "⁋"). So the figures have to be read out of
// the page, and this is the one place in the repository that knows how
// ContraDB's markup is shaped.
//
// Why regexes and a hand-rolled entity decoder rather than a DOM parser: the
// repository has no HTML-parsing dependency and this milestone is not the
// place to add one. The markup being read is machine-generated by one Rails
// template, ~7 KB per page, and is the same on all 2,178 cached pages: a
// table with one class, one <tr> per figure, one <div class="show-figure">
// per row. Regexes over that are exact and fast; they would be the wrong tool
// on arbitrary HTML from the open web.
//
// Nothing here fetches. It reads the cache the crawler wrote
// (scripts/corpus/crawl-contradb.mjs) and writes beside it. A page this
// parser cannot make sense of never crashes the run: it yields a record with
// `figures: []` and a `warnings` array saying why, and --report counts them.
//
// Usage:
//   node scripts/corpus/derive-contradb.mjs
//   node scripts/corpus/derive-contradb.mjs --data ../contra-data
//   node scripts/corpus/derive-contradb.mjs --only 1,3474
//   node scripts/corpus/derive-contradb.mjs --report        # counts, writes nothing

import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(HERE, "../..");

export const BASE_URL = "https://contradb.com";

/** The page URL a ContraDB record was parsed from. */
export function danceUrl(id) {
  return `${BASE_URL}/dances/${id}`;
}

/**
 * Where the private cache lives. `--data` wins, then $CONTRA_DATA (the name
 * docs/corpus-derived.md gives), then $CONTRA_DATA_DIR (the name both
 * crawlers and contra-data/update.sh already export, so a run from there
 * needs no extra environment), then ../contra-data beside the repo.
 */
export function resolveDataRoot({ dataArg = null, env = process.env, repoRoot = REPO_ROOT } = {}) {
  if (dataArg) return resolve(dataArg);
  if (env.CONTRA_DATA) return resolve(env.CONTRA_DATA);
  if (env.CONTRA_DATA_DIR) return resolve(env.CONTRA_DATA_DIR);
  return resolve(repoRoot, "../contra-data");
}

// ---------------------------------------------------------------- HTML bits

// The entities this markup actually produces (&amp;, &#39;, &quot;, &gt;,
// &lt;) plus the handful a transcriber might type. Anything not named here
// and not numeric is left exactly as it came, so an unknown entity is visible
// in the output rather than silently turned into a question mark.
const NAMED_ENTITIES = {
  amp: "&",
  apos: "'",
  bull: "•",
  copy: "©",
  deg: "°",
  frac12: "½",
  frac14: "¼",
  frac34: "¾",
  gt: ">",
  hellip: "…",
  laquo: "«",
  ldquo: "“",
  lsquo: "‘",
  lt: "<",
  mdash: "—",
  middot: "·",
  nbsp: " ",
  ndash: "–",
  quot: '"',
  raquo: "»",
  rdquo: "”",
  reg: "®",
  rsquo: "’",
  times: "×",
};

const ENTITY_RE = /&(#[xX][0-9a-fA-F]+|#\d+|[a-zA-Z][a-zA-Z0-9]*);/g;

/** Decodes named, decimal and hexadecimal HTML entities; leaves the rest. */
export function decodeEntities(text) {
  return text.replace(ENTITY_RE, (whole, body) => {
    if (body[0] !== "#") {
      return Object.hasOwn(NAMED_ENTITIES, body) ? NAMED_ENTITIES[body] : whole;
    }
    const hex = body[1] === "x" || body[1] === "X";
    const code = hex ? Number.parseInt(body.slice(2), 16) : Number.parseInt(body.slice(1), 10);
    if (!Number.isInteger(code) || code < 0 || code > 0x10ffff) return whole;
    try {
      return String.fromCodePoint(code);
    } catch {
      return whole;
    }
  });
}

// An inline tag disappears without a trace — "<u>swing</u>" must become
// "swing", not " swing ". A block tag becomes a space, because the markdown
// blocks in a dance's notes are separate sentences and running them together
// would invent words.
const INLINE_TAGS = new Set([
  "a",
  "b",
  "code",
  "del",
  "em",
  "i",
  "ins",
  "s",
  "span",
  "strong",
  "sub",
  "sup",
  "u",
]);

const TAG_RE = /<\/?([a-zA-Z][a-zA-Z0-9]*)\b[^>]*>/g;
const COMMENT_RE = /<!--[\s\S]*?-->/g;

/** Removes every tag: inline ones leave nothing behind, block ones a space. */
export function stripTags(html) {
  return html
    .replace(COMMENT_RE, " ")
    .replace(TAG_RE, (whole, name) => (INLINE_TAGS.has(name.toLowerCase()) ? "" : " "));
}

/** Whitespace runs (including &nbsp;'s U+00A0) become one space; ends trimmed. */
export function collapseWhitespace(text) {
  return text.replace(/\s+/g, " ").trim();
}

/** Markup in, one line of readable text out: tags off, entities decoded. */
export function plainText(html) {
  return collapseWhitespace(decodeEntities(stripTags(html)));
}

/**
 * The inner HTML of `<div class="<className>" …>`, matching `</div>` by
 * depth — a dance's notes are a markdown block that may contain divs of its
 * own, so a non-greedy match to the first `</div>` would truncate them.
 * `found` is false when the block is absent (several are optional), `closed`
 * false when the page ends before the div does.
 */
export function extractBlock(html, className) {
  const open = new RegExp(`<div class="${className}"[^>]*>`).exec(html);
  if (!open) return { found: false, closed: false, inner: "" };
  const start = open.index + open[0].length;
  const token = /<div\b[^>]*>|<\/div\s*>/g;
  token.lastIndex = start;
  let depth = 1;
  for (let match = token.exec(html); match; match = token.exec(html)) {
    depth += match[0][1] === "/" ? -1 : 1;
    if (depth === 0) return { found: true, closed: true, inner: html.slice(start, match.index) };
  }
  return { found: true, closed: false, inner: "" };
}

// ------------------------------------------------------------- the figures

const TABLE_RE =
  /<table class="table table-bordered table-condensed contra-table-nonfluid">([\s\S]*?)<\/table>/;
const ROW_RE = /<tr\b[^>]*>([\s\S]*?)<\/tr>/g;
const CELL_RE = /<td\b([^>]*)>([\s\S]*?)<\/td>/g;
const FIGURE_DIV_RE = /<div class="show-figure">([\s\S]*?)<\/div>/;
const UNDERLINE_RE = /<u\b[^>]*>([\s\S]*?)<\/u>/g;
const STRIKE_RE = /<s\b[^>]*>([\s\S]*?)<\/s>/g;

// ContraDB's curation guide calls it the "⁋rogress" mark and renders it at
// the end of the figure after which the progression happens. It is data, not
// text, so it comes out of `text` and goes into `progression`.
const PILCROW = "⁋";

/** The marked words inside one figure's HTML, in the order they were marked. */
function lingoMarks(innerHtml, regex) {
  regex.lastIndex = 0;
  const marks = [];
  for (let match = regex.exec(innerHtml); match; match = regex.exec(innerHtml)) {
    const text = plainText(match[1]);
    if (text) marks.push(text);
  }
  return marks;
}

/** The `<td>`s of one row, as `{ attrs, inner }`, in document order. */
function rowCells(rowHtml) {
  CELL_RE.lastIndex = 0;
  const cells = [];
  for (let match = CELL_RE.exec(rowHtml); match; match = CELL_RE.exec(rowHtml)) {
    cells.push({ attrs: match[1], inner: match[2] });
  }
  return cells;
}

/**
 * Parses the figure table out of a whole page. Cells are identified by what
 * they are (the beats cell carries `dance-show-beats`, the figure cell holds
 * a `show-figure` div, the label is whatever is left) rather than by column
 * index, so a template change that adds a column does not silently shift
 * every field by one.
 *
 * A row whose phrase-label cell is blank continues the previous row's phrase:
 * that is exactly what ContraDB means by it, and `startsPhrase` records which
 * kind of row it was.
 */
export function parseFigureTable(html) {
  const warnings = [];
  const table = TABLE_RE.exec(html);
  if (!table) {
    warnings.push("no figure table (contra-table-nonfluid) on the page");
    return { figures: [], warnings };
  }
  const figures = [];
  let phrase = "";
  ROW_RE.lastIndex = 0;
  let rowIndex = -1;
  for (let row = ROW_RE.exec(table[1]); row; row = ROW_RE.exec(table[1])) {
    rowIndex += 1;
    const cells = rowCells(row[1]);
    const figureCell = cells.find((cell) => FIGURE_DIV_RE.test(cell.inner));
    if (!figureCell) {
      // A header row, or a row shaped some way this parser has not seen.
      if (collapseWhitespace(plainText(row[1]))) {
        warnings.push(`row ${rowIndex} has no show-figure cell; skipped`);
      }
      continue;
    }
    const beatsCell = cells.find((cell) => /dance-show-beats/.test(cell.attrs));
    const labelCell = cells.find((cell) => cell !== figureCell && cell !== beatsCell);

    const label = labelCell ? plainText(labelCell.inner) : "";
    if (label) phrase = label;

    const beatsText = beatsCell ? plainText(beatsCell.inner) : "";
    const beats = /^\d+$/.test(beatsText) ? Number(beatsText) : null;
    if (beats === null) {
      warnings.push(
        beatsCell
          ? `row ${rowIndex} has an unreadable beats cell ${JSON.stringify(beatsText)}`
          : `row ${rowIndex} has no beats cell`,
      );
    }

    const innerHtml = FIGURE_DIV_RE.exec(figureCell.inner)[1];
    const decoded = decodeEntities(stripTags(innerHtml));
    const progression = decoded.includes(PILCROW);
    figures.push({
      index: figures.length,
      phrase,
      startsPhrase: label !== "",
      beats,
      text: collapseWhitespace(decoded.split(PILCROW).join(" ")),
      progression,
      lingo: {
        underlined: lingoMarks(innerHtml, UNDERLINE_RE),
        struck: lingoMarks(innerHtml, STRIKE_RE),
      },
    });
  }
  if (figures.length === 0 && warnings.length === 0) {
    warnings.push("figure table has no figure rows");
  }
  return { figures, warnings };
}

// -------------------------------------------------------------- the record

const TITLE_RE = /<h1 class="dance-show-title">([\s\S]*?)<\/h1>/;
// The hook paragraph closes with `</h2>` on every cached page — a typo in
// ContraDB's own template — so the close is whichever of the three arrives
// first, never `</p>` alone.
const HOOK_RE = /<p class="dance-show-hook">([\s\S]*?)<\/(?:p|h2|div)>/;
const CHOREOGRAPHER_RE = /<p class="dance-show-choreographer">([\s\S]*?)<\/p>/;
const FORMATION_RE = /<p class="dance-show-formation">([\s\S]*?)<\/p>/;
const LINK_RE = /<a\b[^>]*>([\s\S]*?)<\/a>/;

/** Text after a label ("formation: improper" → "improper"), label optional. */
function afterLabel(text, label) {
  const prefix = new RegExp(`^${label}\\s*:\\s*`, "i");
  return text.replace(prefix, "").trim();
}

/**
 * One cached page plus its manifest line in, one derived record out. Pure:
 * no filesystem, no clock, so the tests drive it with a string.
 *
 * `manifestLine` supplies the two facts the page itself does not carry —
 * when it was fetched and which publish tier it was in when it was listed.
 * A record can be built without one (warned about, both fields null), because
 * a page on disk with no manifest row is still worth parsing.
 */
export function parseDancePage(html, { id, manifestLine = null } = {}) {
  const warnings = [];

  const titleMatch = TITLE_RE.exec(html);
  if (!titleMatch) warnings.push("no h1.dance-show-title on the page");
  const title = titleMatch ? plainText(titleMatch[1]) : "";

  const choreographerMatch = CHOREOGRAPHER_RE.exec(html);
  let choreographer = "";
  if (!choreographerMatch) {
    warnings.push("no p.dance-show-choreographer on the page");
  } else {
    const link = LINK_RE.exec(choreographerMatch[1]);
    // The name is always a link to the choreographer's page; falling back to
    // the paragraph's own text keeps an unlinked name rather than losing it.
    choreographer = link ? plainText(link[1]) : afterLabel(plainText(choreographerMatch[1]), "by");
  }

  const formationMatch = FORMATION_RE.exec(html);
  if (!formationMatch) warnings.push("no p.dance-show-formation on the page");
  const formation = formationMatch ? afterLabel(plainText(formationMatch[1]), "formation") : "";

  const hookMatch = HOOK_RE.exec(html);
  const hook = hookMatch ? afterLabel(plainText(hookMatch[1]), "hook") : "";

  const preambleBlock = extractBlock(html, "dance-show-preamble");
  if (preambleBlock.found && !preambleBlock.closed) warnings.push("unclosed dance-show-preamble");
  const notesBlock = extractBlock(html, "dance-show-notes");
  if (notesBlock.found && !notesBlock.closed) warnings.push("unclosed dance-show-notes");

  const { figures, warnings: figureWarnings } = parseFigureTable(html);
  warnings.push(...figureWarnings);

  if (!manifestLine) warnings.push("no manifest line for this id");

  return {
    source: "contradb",
    id: String(id),
    url: danceUrl(id),
    fetchedAt: manifestLine?.fetchedAt ?? null,
    publish: manifestLine?.publish ?? null,
    title,
    choreographer,
    formation,
    hook,
    preamble: plainText(preambleBlock.inner),
    notes: plainText(notesBlock.inner),
    figures,
    beats: figures.reduce((sum, figure) => sum + (figure.beats ?? 0), 0),
    warnings,
  };
}

// --------------------------------------------------------------- the files

/**
 * The manifest, as Map<string id, line>. It is append-only and a dance gets a
 * fresh line every time the crawler refetches it, so the LAST line for an id
 * is the current one. Ids are keyed as strings because the derived records
 * use string ids.
 */
export function loadManifest(text) {
  const byId = new Map();
  for (const line of text.split("\n")) {
    if (!line.trim()) continue;
    try {
      const parsed = JSON.parse(line);
      byId.set(String(parsed.id), parsed);
    } catch {
      // A truncated last line from a killed crawl: that id is simply
      // treated as having no manifest row.
    }
  }
  return byId;
}

/** Ids of the cached pages, numerically ascending, so a run is deterministic. */
export function cachedIds(fileNames) {
  return fileNames
    .filter((name) => /^\d+\.html$/.test(name))
    .map((name) => name.slice(0, -5))
    .sort((a, b) => Number(a) - Number(b));
}

// Prettier resolves its config from the path of the file being formatted, so
// this does too, memoised per directory. The private cache has no config of
// its own today, so the output is prettier's defaults; if it ever grows one,
// these files follow it without this script changing.
const prettierOptionsByDir = new Map();

/**
 * The record as bytes: prettier's own JSON shape, formatted by prettier
 * itself rather than by an imitation of it. JSON.stringify's two-space indent
 * is the input, so objects stay expanded and short arrays collapse exactly as
 * they would if someone ran prettier over the file afterwards — which is what
 * makes `prettier` then a second run a no-op, as docs/corpus-derived.md
 * requires. Prettier is already a devDependency of this repository; nothing
 * new was added for it.
 */
export async function formatJson(value, filePath = null) {
  const dir = filePath ? dirname(filePath) : "";
  if (!prettierOptionsByDir.has(dir)) {
    prettierOptionsByDir.set(dir, (filePath ? await resolveConfig(filePath) : null) ?? {});
  }
  return format(JSON.stringify(value, null, 2), {
    ...prettierOptionsByDir.get(dir),
    parser: "json",
  });
}

/**
 * The whole derivation, with every side effect injected so the tests can run
 * it on strings. Returns the records it built and the counts --report prints;
 * writing them is the caller's job, because the bytes go through prettier and
 * that is asynchronous.
 */
export function deriveAll({ ids, readPage, manifestById }) {
  const records = [];
  const counts = {
    pages: ids.length,
    figures: 0,
    progressionMarks: 0,
    withLingo: 0,
    withHook: 0,
    withNotes: 0,
    withPreamble: 0,
    noTable: 0,
    withWarnings: 0,
    unreadable: 0,
  };
  const warningCounts = new Map();
  for (const id of ids) {
    let record;
    try {
      record = parseDancePage(readPage(id), { id, manifestLine: manifestById.get(String(id)) });
    } catch (error) {
      // Belt and braces: a page this parser throws on still produces a
      // record, so one bad page never costs the other 2,177.
      counts.unreadable += 1;
      record = {
        source: "contradb",
        id: String(id),
        url: danceUrl(id),
        fetchedAt: null,
        publish: null,
        title: "",
        choreographer: "",
        formation: "",
        hook: "",
        preamble: "",
        notes: "",
        figures: [],
        beats: 0,
        warnings: [`unreadable page: ${error?.message ?? String(error)}`],
      };
    }
    records.push(record);
    counts.figures += record.figures.length;
    counts.progressionMarks += record.figures.filter((figure) => figure.progression).length;
    if (record.figures.some((f) => f.lingo.underlined.length || f.lingo.struck.length)) {
      counts.withLingo += 1;
    }
    if (record.hook) counts.withHook += 1;
    if (record.notes) counts.withNotes += 1;
    if (record.preamble) counts.withPreamble += 1;
    if (record.figures.length === 0) counts.noTable += 1;
    if (record.warnings.length > 0) counts.withWarnings += 1;
    for (const warning of record.warnings) {
      // Group by shape, not by the row number inside it.
      const kind = warning.replace(/\brow \d+\b/, "row N");
      warningCounts.set(kind, (warningCounts.get(kind) ?? 0) + 1);
    }
  }
  return { records, counts, warningCounts };
}

// ------------------------------------------------------------------- the CLI

export function parseArgs(argv) {
  const args = { data: null, only: null, report: false };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === "--data") {
      args.data = argv[++i];
      if (!args.data) throw new Error("--data requires a path");
    } else if (arg === "--only") {
      const value = argv[++i];
      if (!value) throw new Error("--only requires an id or a comma-separated list of ids");
      args.only = value
        .split(",")
        .map((id) => id.trim())
        .filter(Boolean);
    } else if (arg === "--report") {
      args.report = true;
    } else {
      throw new Error(`unknown argument "${arg}"`);
    }
  }
  return args;
}

async function main() {
  let args;
  try {
    args = parseArgs(process.argv.slice(2));
  } catch (error) {
    console.error(`derive-contradb: ${error.message}`);
    process.exit(1);
  }

  const dataRoot = resolveDataRoot({ dataArg: args.data });
  const rawDir = resolve(dataRoot, "corpus-raw/contradb");
  const outDir = resolve(dataRoot, "derived/contradb");
  if (!existsSync(rawDir)) {
    console.error(`derive-contradb: no raw cache at ${rawDir} (pass --data or set CONTRA_DATA)`);
    process.exit(1);
  }

  const manifestPath = resolve(rawDir, "manifest.jsonl");
  const manifestById = existsSync(manifestPath)
    ? loadManifest(readFileSync(manifestPath, "utf-8"))
    : new Map();

  let ids = cachedIds(readdirSync(rawDir));
  if (args.only) {
    const wanted = new Set(args.only);
    const missing = args.only.filter((id) => !ids.includes(id));
    if (missing.length)
      console.warn(`derive-contradb: no cached page for id(s) ${missing.join(", ")}`);
    ids = ids.filter((id) => wanted.has(id));
  }

  const { records, counts, warningCounts } = deriveAll({
    ids,
    readPage: (id) => readFileSync(resolve(rawDir, `${id}.html`), "utf-8"),
    manifestById,
  });

  if (!args.report) {
    mkdirSync(outDir, { recursive: true });
    for (const record of records) {
      const outPath = resolve(outDir, `${record.id}.json`);
      writeFileSync(outPath, await formatJson(record, outPath));
    }
  }

  console.log(`derive-contradb: ${rawDir} → ${outDir}`);
  console.log(`manifest rows: ${manifestById.size}`);
  console.log(`pages read: ${counts.pages}${args.report ? " (report only, nothing written)" : ""}`);
  console.log(`figures: ${counts.figures}`);
  console.log(`  carrying the progression mark (⁋): ${counts.progressionMarks}`);
  console.log(`dances with at least one lingo mark: ${counts.withLingo}`);
  console.log(`dances with a hook: ${counts.withHook}`);
  console.log(`dances with a preamble: ${counts.withPreamble}`);
  console.log(`dances with notes: ${counts.withNotes}`);
  console.log(`pages with no figures at all: ${counts.noTable}`);
  console.log(`pages the parser threw on: ${counts.unreadable}`);
  console.log(`pages with at least one warning: ${counts.withWarnings}`);
  if (warningCounts.size > 0) {
    console.log("warnings by kind:");
    for (const [kind, count] of [...warningCounts.entries()].sort((a, b) => b[1] - a[1])) {
      console.log(`  ${count}× ${kind}`);
    }
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main();
}
